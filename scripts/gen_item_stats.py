#!/usr/bin/env python3
"""Generate bots/FunLib/item_stats_data.lua from the game's own data files.

Reads scripts/npc/items.txt and scripts/npc/heroes/*.txt (extracted from
game/dota/pak01_dir.vpk) and writes, per purchasable item, its cost and the
stats the bots value (attributes, damage, attack speed, armor, health, mana,
regen, magic resistance, movement, evasion, lifesteal, spell amp, crit,
active), and per hero its primary attribute, attack type and gains.

Usage:
  python3 scripts/gen_item_stats.py <dir with scripts_npc_items.txt and
                                     scripts_npc_heroes_npc_dota_hero_*.txt>
"""
import os
import re
import sys

TOKEN = re.compile(r'"((?:[^"\\]|\\.)*)"|([{}])|//[^\n]*')


def parse_kv(text):
    """Minimal KeyValues parser: returns nested dicts (later keys win)."""
    tokens = []
    for m in TOKEN.finditer(text):
        if m.group(1) is not None:
            tokens.append(('s', m.group(1)))
        elif m.group(2):
            tokens.append((m.group(2), None))
    pos = 0

    def block():
        nonlocal pos
        d = {}
        while pos < len(tokens):
            kind, val = tokens[pos]
            if kind == '}':
                pos += 1
                return d
            if kind != 's':
                pos += 1
                continue
            key = val
            pos += 1
            if pos >= len(tokens):
                break
            k2, v2 = tokens[pos]
            if k2 == '{':
                pos += 1
                d[key] = block()
            elif k2 == 's':
                pos += 1
                d[key] = v2
        return d

    return block()


# AbilityValues key -> stat. First number of a multi-level value is used.
STAT_KEYS = {
    'str': ['bonus_strength', 'bonus_str'],
    'agi': ['bonus_agility', 'bonus_agi'],
    'int': ['bonus_intellect', 'bonus_intelligence', 'bonus_int'],
    'all': ['bonus_all_stats', 'bonus_stats', 'bonus_attributes'],
    'dmg': ['bonus_damage'],
    'as': ['bonus_attack_speed'],
    'armor': ['bonus_armor'],
    'hp': ['bonus_health'],
    'mana': ['bonus_mana'],
    'hpr': ['bonus_health_regen', 'bonus_hp_regen', 'hp_regen', 'bonus_regen', 'health_regen'],
    'mpr': ['bonus_mana_regen', 'mana_regen'],
    'mr': ['bonus_magical_armor', 'bonus_spell_resist', 'magic_resistance', 'bonus_magic_resistance'],
    'ms': ['bonus_movement_speed', 'movement_speed'],
    'evasion': ['bonus_evasion', 'evasion'],
    'lifesteal': ['lifesteal_percent', 'lifesteal'],
    'spell_amp': ['spell_amp', 'bonus_spell_amp'],
    'crit': ['crit_multiplier'],
    'crit_chance': ['crit_chance'],
    'status': ['status_resistance', 'bonus_status_resistance'],
    'cdr': ['bonus_cooldown'],
}


def first_number(v):
    if isinstance(v, dict):
        v = v.get('value', '')
    m = re.search(r'-?\d+(\.\d+)?', str(v))
    return float(m.group(0)) if m else None


def item_stats(name, data):
    av = data.get('AbilityValues') or {}
    out = {}
    for stat, keys in STAT_KEYS.items():
        for k in keys:
            if k in av:
                n = first_number(av[k])
                if n:
                    out[stat] = n
                    break
    if any(str(k).startswith('aura_') for k in av):
        out['aura'] = 1
    behavior = data.get('AbilityBehavior', '')
    out['active'] = 1 if ('PASSIVE' not in behavior and behavior) else 0
    return out


def lua_value(v):
    if isinstance(v, float) and v.is_integer():
        return str(int(v))
    return str(v)


def main():
    src = sys.argv[1]
    items = parse_kv(open(os.path.join(src, 'scripts_npc_items.txt'), encoding='utf-8', errors='replace').read())
    items = items.get('DOTAAbilities', items)
    lines = ['-- Generated by scripts/gen_item_stats.py from the game files. Do not edit.',
             '-- Items: cost and stats; heroes: primary attribute, attack type, gains.',
             'local X = {}', '', 'X.Items = {']
    for name in sorted(items):
        data = items[name]
        if not isinstance(data, dict) or not name.startswith('item_') or name.startswith('item_recipe_'):
            continue
        cost = first_number(data.get('ItemCost', '0')) or 0
        if cost <= 0 or data.get('ItemPurchasable', '1') == '0' or data.get('IsObsolete') == '1':
            continue
        st = item_stats(name, data)
        fields = ['cost = %s' % lua_value(cost)] + ['%s = %s' % (k, lua_value(v)) for k, v in sorted(st.items()) if v]
        lines.append('\t%s = { %s },' % (name, ', '.join(fields)))
    lines += ['}', '', '-- In the item files but not in the shop any more (removed by a patch).', 'X.Obsolete = {']
    for name in sorted(items):
        data = items[name]
        if isinstance(data, dict) and name.startswith('item_') and not name.startswith('item_recipe_') \
                and (data.get('IsObsolete') == '1' or data.get('ItemPurchasable', '1') == '0'):
            lines.append('\t%s = true,' % name)
    lines += ['}', '', '-- Every item the game knows (shop or not).', 'X.Known = {']
    for name in sorted(items):
        if isinstance(items[name], dict) and name.startswith('item_'):
            lines.append('\t%s = true,' % name)
    lines += ['}', '', 'X.Heroes = {']
    for fn in sorted(os.listdir(src)):
        m = re.match(r'scripts_npc_heroes_(npc_dota_hero_\w+)\.txt$', fn)
        if not m or m.group(1).endswith('_base'):
            continue
        kv = parse_kv(open(os.path.join(src, fn), encoding='utf-8', errors='replace').read())
        heroes = kv.get('DOTAHeroes', kv)
        h = heroes.get(m.group(1))
        if not isinstance(h, dict):
            continue
        attr = {'DOTA_ATTRIBUTE_STRENGTH': 'str', 'DOTA_ATTRIBUTE_AGILITY': 'agi',
                'DOTA_ATTRIBUTE_INTELLECT': 'int', 'DOTA_ATTRIBUTE_ALL': 'all'}.get(h.get('AttributePrimary', ''), 'all')
        ranged = 1 if 'RANGED' in h.get('AttackCapabilities', '') else 0
        gains = [first_number(h.get(k, '0')) or 0 for k in ('AttributeStrengthGain', 'AttributeAgilityGain', 'AttributeIntelligenceGain')]
        lines.append("\t%s = { attr = '%s', ranged = %d, bat = %s, gain = { %s } }," % (
            m.group(1), attr, ranged, lua_value(first_number(h.get('AttackRate', '1.7')) or 1.7),
            ', '.join(lua_value(g) for g in gains)))
    lines += ['}', '', 'return X', '']
    out = os.path.join(os.path.dirname(__file__), '..', 'bots', 'FunLib', 'item_stats_data.lua')
    open(out, 'w').write('\n'.join(lines))
    print('wrote', out)


if __name__ == '__main__':
    main()
